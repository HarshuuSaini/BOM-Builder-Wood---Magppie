const assert = require('node:assert/strict');
require('./test-purchase-rounding.cjs');
const { WastageControls } = require('../src/components/WastageControls.tsx');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const waste = { carcass: 12, shutter: 22, profile: 12, edgeBand: 3 };
const overrides = { 'foil:shutter': 10, 'foil:visible': 15, 'KITCHEN-086': 7 };
let nextWaste, nextOverrides;
const props = { waste, overrides, admin: true, onWaste: value => { nextWaste = value; }, onOverrides: value => { nextOverrides = value; } };
const inputs = [];
function visit(node) { if (!node || typeof node !== 'object') return; if (Array.isArray(node)) return node.forEach(visit); if (node.type === 'input') inputs.push(node.props); visit(node.props?.children); }
visit(WastageControls(props));
assert.equal(inputs.length, 10);
const find = label => inputs.find(p => p['aria-label'] === label);
assert.equal(find('foil group waste percent').placeholder, 'Mixed');
find('foil group waste percent').onChange({ target: { value: '18' } });
assert.equal(nextOverrides['foil:shutter'], 18); assert.equal(nextOverrides['foil:visible'], 18);
assert.equal(nextOverrides['KITCHEN-086'], 7, 'Other saved overrides are preserved');
find('light profile / diffuser group waste percent').onChange({ target: { value: '0' } });
assert.equal(nextOverrides['KITCHEN-084'], 0); assert.equal(nextOverrides['KITCHEN-085'], 0);
find('shutter waste percent').onChange({ target: { value: '30' } });
assert.equal(nextWaste.shutter, 30); assert.equal(waste.shutter, 22);
find('foil group waste percent').onChange({ target: { value: '' } });
assert(!Object.hasOwn(nextOverrides, 'foil:shutter') && !Object.hasOwn(nextOverrides, 'foil:visible'));
const html = renderToStaticMarkup(React.createElement(WastageControls, props));
assert(html.includes('skirting group waste percent') && !html.includes('ALU PROF FOR'));
const designer = renderToStaticMarkup(React.createElement(WastageControls, { ...props, admin: false }));
assert.equal((designer.match(/<input/g) ?? []).length, 4);
console.log('PASS: shared grouped wastage controls, mixed values, linked foil/profile updates, default reset, immutable draft values and admin-only groups.');
