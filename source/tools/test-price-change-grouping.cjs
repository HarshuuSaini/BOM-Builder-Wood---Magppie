const assert = require('node:assert/strict');
require('./test-purchase-rounding.cjs');
const { priceChangesFor, groupPriceChanges, missingPriceReasons, validPriceChanges } = require('../src/lib/price-change-audit.ts');
const { PriceChangeSummary } = require('../src/components/PriceChangeSummary.tsx');
const { PriceChangeReview } = require('../src/components/PriceChangeReview.tsx');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const choice = { itemId: 'KITCHEN-007', boardSheetPrice: '3875', frontSheetPrice: '1150', backSheetPrice: '1150' };
const entry = { rows: [], materials: { Base: { carcass: choice }, Wall: { carcass: { ...choice } } } };
const changes = priceChangesFor(entry);
const before = JSON.stringify(changes);
const rows = groupPriceChanges(changes);
assert.equal(changes.length, 6);
assert.equal(rows.length, 2, 'One board row and one laminate row replace repeated zone/face fields');
const board = rows.find(r => r.rateType === 'Board'), laminate = rows.find(r => r.rateType === 'Laminate');
assert.equal(board.defaultPrice, 2612.4); assert.equal(board.changedPrice, 3875); assert.equal(board.keys.length, 2);
assert.equal(laminate.defaultPrice, 550); assert.equal(laminate.changedPrice, 1150); assert.equal(laminate.keys.length, 4);
assert(laminate.usages.some(s => s.includes('Front face')) && laminate.usages.some(s => s.includes('Back face')));
assert(board.usages.some(s => s.includes('Base')) && board.usages.some(s => s.includes('Wall')));
const differentReasons = changes.map(c => ({ ...c, reason: c.key.startsWith('Materials.Wall') ? 'Wall supplier' : 'Base supplier' }));
assert.equal(groupPriceChanges(differentReasons).length, 4, 'Different reasons cannot be hidden by grouping');
const justified = changes.map(c => ({ ...c, reason: 'new accessory ' }));
const normalized = priceChangesFor({ ...entry, priceChanges: justified });
assert(normalized.every(c => c.reason === 'new accessory '), 'Trailing spaces survive each render while typing the next word');
assert(groupPriceChanges(normalized).every(c => c.reason === 'new accessory '));
const long = 'Customer requested this accessory. '.repeat(100);
const longRemarks = changes.map(c => ({ ...c, reason: long }));
assert(validPriceChanges(longRemarks), 'Remarks longer than 1,000 characters are accepted');
assert.equal(missingPriceReasons(priceChangesFor({ ...entry, priceChanges: longRemarks })).length, 0);
assert.equal(missingPriceReasons(changes.map(c => ({ ...c, reason: '   ' }))).length, 6, 'A blank-only remark is still invalid');
const html = renderToStaticMarkup(React.createElement(PriceChangeSummary, { changes: normalized }));
assert(html.includes('POSTlam BWP Ply BSL-18mm') && html.includes('Laminate 0.8 mm'));
assert(!html.includes('Materials ·') && !html.includes('boardSheetPrice'));
const review = renderToStaticMarkup(React.createElement(PriceChangeReview, { changes: normalized, onReason() {} }));
assert.equal((review.match(/<textarea/g) ?? []).length, 2);
assert(!/maxlength/i.test(review), 'The remark editor has no character cap');
assert.equal(JSON.stringify(changes), before, 'Grouping cannot alter saved prices or validation records');
console.log('PASS: material grouping, separate board/laminate prices, zone/face usages, distinct reasons, shared single-kitchen summary, preserved spaces and uncapped remarks.');
